// Builds /home.css from styles/home.src.css plus the shared section of /seo-site.css.
// Edit shared header, navigation, button and footer rules once, in seo-site.css above the marker.
const fs = require('node:fs'), path = require('node:path');
const root = path.resolve(__dirname, '..');
const marker = '/* ==== end of shared rules';
const seo = fs.readFileSync(path.join(root, 'seo-site.css'), 'utf8');
const at = seo.indexOf(marker);
if (at < 0) throw new Error('seo-site.css: shared-section marker missing');
const source = fs.readFileSync(path.join(root, 'styles/home.src.css'), 'utf8');
if (!source.includes('/* @include-shared */\n')) throw new Error('styles/home.src.css: /* @include-shared */ line missing');
const banner = '/* GENERATED by scripts/styles.cjs. Do not edit: change styles/home.src.css or the shared section of seo-site.css, then run npm run build. */\n';
const out = banner + source.replace('/* @include-shared */\n', seo.slice(0, at));
const file = path.join(root, 'home.css');
if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== out) fs.writeFileSync(file, out);
console.log('Built home.css from styles/home.src.css and the shared section of seo-site.css.');
